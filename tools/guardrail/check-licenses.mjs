#!/usr/bin/env node
/**
 * Dependency licence guardrail. Lists every production npm package and every Rust
 * crate compiled into the Windows apps, fails on any licence outside the allowed
 * set, and keeps docs/licenses/*.md in sync (`--write` regenerates them).
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const write = process.argv.includes('--write');

// Permissive licences, plus MPL-2.0 (file-level copyleft; we ship unmodified files)
// and OFL-1.1 (fonts). Anything else needs an explicit decision record.
const ALLOWED = new Set([
  'MIT',
  'MIT-0',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  '0BSD',
  'Zlib',
  'Unicode-3.0',
  'Unicode-DFS-2016',
  'MPL-2.0',
  'Unlicense',
  'CC0-1.0',
  'BSL-1.0',
  'OFL-1.1',
]);

/** Evaluates an SPDX expression: OR needs one allowed side, AND needs both. */
function allowed(expr) {
  let s = expr
    .replaceAll('/', ' OR ')
    .replace(/\s+WITH\s+[\w.-]+/g, '')
    .trim();
  const strip = (x) => {
    x = x.trim();
    while (x.startsWith('(') && x.endsWith(')') && balanced(x.slice(1, -1)))
      x = x.slice(1, -1).trim();
    return x;
  };
  const balanced = (x) => {
    let d = 0;
    for (const c of x) {
      if (c === '(') d++;
      if (c === ')' && --d < 0) return false;
    }
    return d === 0;
  };
  const split = (x, op) => {
    const parts = [];
    let depth = 0;
    let cur = '';
    const tokens = x.split(/(\(|\)|\s+)/).filter((t) => t !== '');
    for (const t of tokens) {
      if (t === '(') depth++;
      if (t === ')') depth--;
      if (depth === 0 && t === op) {
        parts.push(cur);
        cur = '';
      } else cur += t;
    }
    parts.push(cur);
    return parts.map(strip);
  };
  const ev = (x) => {
    x = strip(x);
    const ors = split(x, 'OR');
    if (ors.length > 1) return ors.some(ev);
    const ands = split(x, 'AND');
    if (ands.length > 1) return ands.every(ev);
    return ALLOWED.has(x);
  };
  return ev(s);
}

const run = (cmd, args) =>
  execFileSync(cmd, args, { cwd: repo, encoding: 'utf8', maxBuffer: 64 << 20 });

// npm production dependencies (all workspaces).
const npm = [];
for (const [license, pkgs] of Object.entries(
  JSON.parse(run('pnpm', ['licenses', 'list', '--prod', '--json'])),
))
  for (const p of pkgs) for (const v of p.versions) npm.push({ name: p.name, version: v, license });
npm.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// Rust crates built for the Windows target.
const meta = JSON.parse(
  run('cargo', [
    'metadata',
    '--format-version',
    '1',
    '--locked',
    '--filter-platform',
    'x86_64-pc-windows-msvc',
  ]),
);
const members = new Set(meta.workspace_members);
const reachable = new Set(meta.resolve.nodes.map((n) => n.id));
const rust = meta.packages
  .filter((p) => !members.has(p.id) && reachable.has(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? 'UNKNOWN' }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const bad = [
  ...npm.map((p) => ({ ...p, eco: 'npm' })),
  ...rust.map((p) => ({ ...p, eco: 'cargo' })),
].filter((p) => !allowed(p.license));

const table = (title, rows, note) =>
  `# ${title}\n\n<!-- Generated by tools/guardrail/check-licenses.mjs --write. Do not edit. -->\n\n${note}\n\n` +
  `| Package | Version | Licence |\n| --- | --- | --- |\n` +
  rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join('\n') +
  '\n';

const outputs = {
  'docs/licenses/npm-production.md': table(
    'npm production dependencies',
    npm,
    `${npm.length} packages shipped in the Studio and Viewer front ends.`,
  ),
  'docs/licenses/rust-crates.md': table(
    'Rust crates (Windows x64 build)',
    rust,
    `${rust.length} crates compiled into the Windows binaries (including build-time crates).`,
  ),
};

let stale = 0;
for (const [path, body] of Object.entries(outputs)) {
  const abs = join(repo, path);
  const cur = existsSync(abs) ? readFileSync(abs, 'utf8').replaceAll('\r\n', '\n') : '';
  if (cur === body) continue;
  if (write) {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body);
  } else {
    console.error(`stale: ${path} (run \`node tools/guardrail/check-licenses.mjs --write\`)`);
    stale++;
  }
}

if (bad.length) {
  console.error('Licences outside the allowed set (add a docs/decisions entry before allowing):');
  for (const p of bad) console.error(`  ${p.eco} ${p.name}@${p.version}: ${p.license}`);
}
if (bad.length || stale) process.exit(1);
console.log(
  `Licence guardrail: ${npm.length} npm + ${rust.length} Rust dependencies, all allowed.`,
);
