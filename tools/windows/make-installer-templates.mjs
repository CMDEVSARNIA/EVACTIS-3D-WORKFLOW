#!/usr/bin/env node
/**
 * Derives the per-app NSIS and WiX templates from the vendored tauri-bundler
 * templates (packaging/windows/upstream). Changes, all required by the brief:
 *
 *  - default install path  C:\Program Files\EVACTIS\3DWORKFLOW\<App>  (per-machine)
 *                          %LOCALAPPDATA%\Programs\EVACTIS\3DWORKFLOW\<App> (per-user)
 *  - Start menu folder "EVACTIS 3DWORKFLOW" with shortcut "3DWORKFLOW <App>"
 *  - branded file-type icons for .evxproj / .evx instead of the exe icon
 *  - the WebView2 offline installer is always embedded from the file named by the
 *    TAURI_EVX_WEBVIEW2_INSTALLER environment variable at build time (TAURI prefix: the
 *    bundler strips every other variable before running WiX), with tauri.conf.json
 *    set to webviewInstallMode "skip": the bundler's own offlineInstaller mode makes
 *    a network request on every build, which breaks air-gapped builds (ADR 0003)
 *
 * Every patch must match exactly once (or the stated count) so an upstream change
 * cannot slip through silently. `--check` verifies the committed output.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const up = (f) => readFileSync(join(repo, 'packaging/windows/upstream', f), 'utf8');
const check = process.argv.includes('--check');

const APPS = [
  { dir: 'studio', folder: 'Studio', shortcut: '3DWORKFLOW Studio' },
  { dir: 'viewer-desktop', folder: 'Viewer', shortcut: '3DWORKFLOW Viewer' },
];

function patch(src, find, replace, count = 1) {
  const parts = src.split(find);
  if (parts.length - 1 !== count)
    throw new Error(`Patch expected ${count} match(es), found ${parts.length - 1}:\n${find}`);
  return parts.join(replace);
}

function nsis(app) {
  const sub = `EVACTIS\\3DWORKFLOW\\${app.folder}`;
  let s = up('installer.nsi');
  s = patch(
    s,
    '!define MULTIUSER_INSTALLMODE_INSTDIR "${PRODUCTNAME}"',
    `!define MULTIUSER_INSTALLMODE_INSTDIR "${sub}"`,
  );
  s = patch(
    s,
    'StrCpy $INSTDIR "$PROGRAMFILES64\\${PRODUCTNAME}"',
    `StrCpy $INSTDIR "$PROGRAMFILES64\\${sub}"`,
    2,
  );
  s = patch(
    s,
    'StrCpy $INSTDIR "$PROGRAMFILES\\${PRODUCTNAME}"',
    `StrCpy $INSTDIR "$PROGRAMFILES\\${sub}"`,
    2,
  );
  s = patch(
    s,
    'StrCpy $INSTDIR "$LOCALAPPDATA\\${PRODUCTNAME}"',
    `StrCpy $INSTDIR "$LOCALAPPDATA\\Programs\\${sub}"`,
  );
  const lnk = s.split('${PRODUCTNAME}.lnk').length - 1;
  if (lnk < 6) throw new Error(`Expected shortcut references, found ${lnk}`);
  s = s.replaceAll('${PRODUCTNAME}.lnk', `${app.shortcut}.lnk`);
  s = patch(
    s,
    '"$INSTDIR\\${MAINBINARYNAME}.exe,0" "Open with ${PRODUCTNAME}"',
    '"$INSTDIR\\filetypes\\\\{{ext}}.ico" "Open with ${PRODUCTNAME}"',
  );
  s = patch(
    s,
    '!define INSTALLWEBVIEW2MODE "{{install_webview2_mode}}"',
    '!define INSTALLWEBVIEW2MODE "offlineInstaller"',
  );
  s = patch(
    s,
    '!define WEBVIEW2INSTALLERARGS "{{webview2_installer_args}}"',
    '!define WEBVIEW2INSTALLERARGS "/silent"',
  );
  // $%VAR% is expanded by makensis at compile time; an unset variable fails the File command.
  s = patch(
    s,
    '!define WEBVIEW2INSTALLERPATH "{{webview2_installer_path}}"',
    '!define WEBVIEW2INSTALLERPATH "$%TAURI_EVX_WEBVIEW2_INSTALLER%"',
  );
  return `; Generated by tools/windows/make-installer-templates.mjs from tauri-bundler 2.10.2. Do not edit.\n${s}`;
}

function wix(app) {
  let s = up('main.wxs');
  s = patch(
    s,
    '<Directory Id="INSTALLDIR" Name="{{product_name}}"/>',
    `<Directory Id="EvxCompanyFolder" Name="EVACTIS">
                    <Directory Id="EvxProductFolder" Name="3DWORKFLOW">
                        <Directory Id="INSTALLDIR" Name="${app.folder}"/>
                    </Directory>
                </Directory>`,
  );
  s = patch(
    s,
    '<Directory Id="ApplicationProgramsFolder" Name="{{product_name}}"/>',
    '<Directory Id="ApplicationProgramsFolder" Name="EVACTIS 3DWORKFLOW"/>',
  );
  s = patch(
    s,
    '<Shortcut Id="ApplicationDesktopShortcut" Name="{{product_name}}"',
    `<Shortcut Id="ApplicationDesktopShortcut" Name="${app.shortcut}"`,
  );
  s = patch(
    s,
    `<Shortcut Id="ApplicationStartMenuShortcut"
                    Name="{{product_name}}"`,
    `<Shortcut Id="ApplicationStartMenuShortcut"
                    Name="${app.shortcut}"`,
  );
  // Non-advertised associations so each type gets its own branded icon.
  s = patch(
    s,
    `                {{#each file_associations as |association| ~}}
                {{#each association.ext as |ext| ~}}
                <ProgId Id="{{../../product_name}}.{{ext}}" Advertise="yes" Description="{{association.description}}">
                    <Extension Id="{{ext}}" Advertise="yes">
                        <Verb Id="open" Command="Open with {{../../product_name}}" Argument="&quot;%1&quot;" />
                    </Extension>
                </ProgId>
                {{/each~}}
                {{/each~}}`,
    `                {{#each file_associations as |association| ~}}
                {{#each association.ext as |ext| ~}}
                <RegistryKey Root="HKLM" Key="Software\\Classes\\.{{ext}}">
                    <RegistryValue Type="string" Value="{{association.name}}" />
                </RegistryKey>
                <RegistryKey Root="HKLM" Key="Software\\Classes\\\\{{association.name}}">
                    <RegistryValue Type="string" Value="{{association.description}}" />
                    <RegistryKey Key="DefaultIcon">
                        <RegistryValue Type="string" Value="[INSTALLDIR]filetypes\\\\{{ext}}.ico" />
                    </RegistryKey>
                    <RegistryKey Key="shell\\open\\command">
                        <RegistryValue Type="string" Value="&quot;[!Path]&quot; &quot;%1&quot;" />
                    </RegistryKey>
                </RegistryKey>
                {{/each~}}
                {{/each~}}`,
  );
  // WebView2: always embed the offline installer (product_name is always set, so these
  // blocks render even though the bundler is told to skip WebView2).
  s = patch(s, '{{#if install_webview}}', '{{#if product_name}}');
  s = patch(s, '{{#if webview2_installer_path}}', '{{#if product_name}}');
  s = patch(
    s,
    `<Binary Id="MicrosoftEdgeWebView2RuntimeInstaller.exe" SourceFile="{{webview2_installer_path}}"/>
        <CustomAction Id='InvokeStandalone' BinaryKey='MicrosoftEdgeWebView2RuntimeInstaller.exe' Execute="deferred" ExeCommand='{{webview_installer_args}} /install' Return='check' />`,
    `<Binary Id="MicrosoftEdgeWebView2RuntimeInstaller.exe" SourceFile="$(env.TAURI_EVX_WEBVIEW2_INSTALLER)"/>
        <CustomAction Id='InvokeStandalone' BinaryKey='MicrosoftEdgeWebView2RuntimeInstaller.exe' Execute="deferred" ExeCommand='/silent /install' Return='check' />`,
  );
  return `<!-- Generated by tools/windows/make-installer-templates.mjs from tauri-bundler 2.10.2. Do not edit. -->\n${s}`;
}

/**
 * Handlebars treats a backslash right before `{{` as an escape and prints the
 * expression literally (e.g. a registry key named "{{ext}}"). Windows paths must use
 * `\\{{`, as upstream does.
 */
function assertNoEscapedMustache(name, body) {
  const m = /(^|[^\\])\\\{\{/m.exec(body);
  if (m) {
    const line = body.slice(0, m.index).split('\n').length;
    throw new Error(`${name}:${line}: "\\{{" is a Handlebars escape; write "\\\\{{"`);
  }
}

let stale = 0;
for (const app of APPS) {
  for (const [name, body] of [
    ['installer.nsi', nsis(app)],
    ['main.wxs', wix(app)],
  ]) {
    assertNoEscapedMustache(name, body);
    const out = join(repo, 'apps', app.dir, 'src-tauri/windows', name);
    const current = existsSync(out) ? readFileSync(out, 'utf8').replaceAll('\r\n', '\n') : '';
    if (current === body) continue;
    if (check) {
      console.error(`stale: ${out}`);
      stale++;
    } else writeFileSync(out, body);
  }
}
if (stale) {
  console.error('Run `pnpm installers:templates`.');
  process.exit(1);
}
console.log(check ? 'Installer templates are up to date.' : 'Installer templates written.');
