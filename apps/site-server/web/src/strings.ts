export const STRINGS = { en, fr };
export type Lang = keyof typeof STRINGS;

const KEY = 'evx-site-lang';
export function language(): Lang {
  try {
    const stored = localStorage.getItem(KEY);
    if (stored === 'en' || stored === 'fr') return stored;
  } catch {
    // storage blocked: fall back to the browser language
  }
  return navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}
export function setLanguage(l: Lang): void {
  try {
    localStorage.setItem(KEY, l);
  } catch {
    // not remembered; still switched for this page
  }
}
export const localized = (title: Record<string, string>, lang: Lang) =>
  title[lang] ?? title.en ?? Object.values(title)[0] ?? '';
