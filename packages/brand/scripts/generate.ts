/**
 * Generates every derived brand asset from the sources in packages/brand/src and the
 * reference measurements in /brand. Run `pnpm brand:generate` after changing a
 * source; `--check` fails if any committed output is stale (used by `pnpm check`).
 *
 * Outputs:
 *   src/generated/wordmark.ts      wordmark + "3DWORKFLOW" outlines (Poppins ExtraBold)
 *   src/tokens.css                 CSS custom properties
 *   *.svg                          logo mark, logo lockup, product lockups
 *   svg/{icons,buttons,markers,signs}/*.svg
 *   fonts/                         bundled Inter woff2 + OFL licence; fonts/print/ static
 *                                  Inter weights for PDFs
 *   generated/print/               sign and lockup PNGs for printed plans
 *   apps/{studio,viewer-desktop}/src-tauri/icons/   app + file-type icons
 *   apps/{studio,viewer-desktop}/src-tauri/windows/ NSIS + WiX bitmaps
 */
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { encodeBmp, encodeIco, renderSvg } from './raster.ts';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js') as typeof import('opentype.js');

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const repo = resolve(pkg, '../..');
const check = process.argv.includes('--check');
const stale: string[] = [];
let written = 0;

function emit(path: string, data: string | Buffer): void {
  const abs = resolve(pkg, path);
  const buf = typeof data === 'string' ? Buffer.from(data) : data;
  const current = existsSync(abs) ? readFileSync(abs) : null;
  if (current && current.equals(buf)) return;
  if (check) {
    stale.push(relative(repo, abs));
    return;
  }
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, buf);
  written++;
}

// ---------------------------------------------------------------------------
// 1. Wordmark outlines
// ---------------------------------------------------------------------------
// Placement measured from brand/website-home-hero.png and expressed in logo-mark
// units (mark height 564): "VACTIS" cap top 250, baseline 516, from x 687 to 2065.
const CAP_TOP = 250;
const BASELINE = 516;
const VACTIS_LEFT = 687;
const VACTIS_RIGHT = 2065;
const WORD_GAP = 140;

const poppins = opentype.loadSync(
  join(pkg, 'node_modules/@fontsource/poppins/files/poppins-latin-800-normal.woff'),
);
const capBox = poppins.getPath('H', 0, 0, 1000).getBoundingBox();
const fontSize = ((BASELINE - CAP_TOP) / (capBox.y2 - capBox.y1)) * 1000;
const scale = fontSize / poppins.unitsPerEm;

type Color = 'navy' | 'greenStrong';
interface Glyph {
  d: string;
  color: Color;
}

/** Lays out `text` with kerning and extra tracking; returns glyph paths and ink bounds. */
function layout(text: string, x0: number, tracking: number, colorOf: (i: number) => Color) {
  const glyphs = poppins.stringToGlyphs(text);
  let x = x0;
  const out: Glyph[] = [];
  let left = Infinity;
  let right = -Infinity;
  glyphs.forEach((g, i) => {
    const path = g.getPath(x, BASELINE, fontSize);
    const bb = path.getBoundingBox();
    left = Math.min(left, bb.x1);
    right = Math.max(right, bb.x2);
    out.push({ d: path.toPathData(1), color: colorOf(i) });
    const next = glyphs[i + 1];
    const kern = next ? poppins.getKerningValue(g, next) : 0;
    x += ((g.advanceWidth ?? 0) + kern) * scale + tracking;
  });
  return { glyphs: out, left, right };
}

// Solve tracking so "VACTIS" spans exactly the measured width, starting at the measured left.
const natural = layout('VACTIS', 0, 0, () => 'navy');
const tracking = (VACTIS_RIGHT - VACTIS_LEFT - (natural.right - natural.left)) / 5;
const vactis = layout('VACTIS', VACTIS_LEFT - natural.left, tracking, (i) =>
  i === 4 ? 'greenStrong' : 'navy',
);
const productProbe = layout('3DWORKFLOW', 0, tracking, () => 'navy');
const product = layout('3DWORKFLOW', VACTIS_RIGHT + WORD_GAP - productProbe.left, tracking, (i) =>
  i < 2 ? 'greenStrong' : 'navy',
);

const wordmarkTs = `// Generated by scripts/generate.ts from Poppins ExtraBold (SIL OFL 1.1). Do not edit.
// Units: logo-mark pixels (mark height 564). Cap height ${BASELINE - CAP_TOP}, baseline ${BASELINE}.
export const WORDMARK = {
  capTop: ${CAP_TOP},
  baseline: ${BASELINE},
  vactisRight: ${vactis.right.toFixed(1)},
  productLeft: ${product.left.toFixed(1)},
  productRight: ${product.right.toFixed(1)},
  vactis: ${JSON.stringify(vactis.glyphs, null, 2).replace(/"(d|color)":/g, '$1:')},
  product: ${JSON.stringify(product.glyphs, null, 2).replace(/"(d|color)":/g, '$1:')},
} as const;
`;
emit('src/generated/wordmark.ts', wordmarkTs);

// Import after the wordmark exists so logo.ts sees the current outlines.
