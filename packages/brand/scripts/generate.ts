const M = logo.MARK;
const markInner = logo.logoMarkSvg().replace(/^<svg[^>]*>(<title>[^<]*<\/title>)?/, '').replace(/<\/svg>$/, '');

/** App icon: the mark on a white rounded tile (keeps the navy mark legible on dark taskbars). */
function appIconSvg(): string {
  const S = 1024;
  const pad = 150;
  const s = (S - 2 * pad) / M.width;
  const y = (S - M.height * s) / 2;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}">` +
    `<rect x="24" y="24" width="${S - 48}" height="${S - 48}" rx="190" fill="${colors.paper}" stroke="#D5D9DE" stroke-width="12"/>` +
    `<g transform="translate(${pad} ${y}) scale(${s})">${markInner}</g></svg>`
  );
}

/** File-type icon: page with folded corner, mark, coloured band (navy = project, green = environment). */
function fileIconSvg(band: string): string {
  const s = 480 / M.width;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">` +
    `<path d="M200 40h460l200 200v744H200z" fill="#FFFFFF" stroke="#B9C0C8" stroke-width="16" stroke-linejoin="round"/>` +
    `<path d="M660 40v200h200" fill="#E8ECF0" stroke="#B9C0C8" stroke-width="16" stroke-linejoin="round"/>` +
    `<rect x="208" y="800" width="644" height="176" fill="${band}"/>` +
    `<g transform="translate(290 300) scale(${s})">${markInner}</g></svg>`
  );
}

const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256];
const ico = (svg: string) => encodeIco(ICO_SIZES.map((size) => ({ size, png: renderSvg(svg, size).png })));

const appIcon = appIconSvg();
const appIco = ico(appIcon);
const projectIco = ico(fileIconSvg(colors.navy));
const envIco = ico(fileIconSvg(colors.greenStrong));
const png = (w: number) => renderSvg(appIcon, w).png;

// Installer artwork.
const stacked = logo.productLockupStackedSvg();
const stackedInner = stacked.replace(/^<svg[^>]*>(<title>[^<]*<\/title>)?/, '').replace(/<\/svg>$/, '');
const sv = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(stacked)!;
const stackW = Number(sv[1]);
const stackH = Number(sv[2]);
const productInner = logo
  .productLockupSvg()
  .replace(/^<svg[^>]*>(<title>[^<]*<\/title>)?/, '')
  .replace(/<\/svg>$/, '');
const prodW = logo.WORDMARK.productRight;

const place = (inner: string, w: number, x: number, y: number, width: number) =>
  `<g transform="translate(${x} ${y}) scale(${width / w})">${inner}</g>`;

const glowBg = (w: number, h: number) =>
  `<clipPath id="glow-clip"><rect width="${w}" height="${h}"/></clipPath>` +
  `<g clip-path="url(#glow-clip)"><rect width="${w}" height="${h}" fill="${colors.ink}"/>` +
  `<circle cx="${w * 0.95}" cy="${h * 0.02}" r="${h * 0.55}" fill="${colors.surfaceDark}"/>` +
  `<circle cx="${-w * 0.1}" cy="${h * 1.02}" r="${h * 0.38}" fill="${colors.surfaceDark}"/></g>`;

function plate(x: number, y: number, w: number, h: number) {
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${h * 0.12}" fill="${colors.paper}"/>`;
}

