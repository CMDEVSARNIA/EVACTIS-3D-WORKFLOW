const logo = await import('../src/logo.ts');
const { ICON_NAMES, iconSvg } = await import('../src/icons.ts');
const { evacMarkerSvg, infoMarkerSvg } = await import('../src/markers.ts');
const { SIGN_NAMES, signSvg } = await import('../src/signs.ts');

// ---------------------------------------------------------------------------
// 2. Tokens, logos, kit SVGs
// ---------------------------------------------------------------------------
emit('src/tokens.css', tokensToCss());
emit('logo-mark.svg', logo.logoMarkSvg() + '\n');
emit('logo-lockup.svg', logo.logoLockupSvg() + '\n');
emit('logo-lockup-plate.svg', logo.logoLockupSvg({ plate: true }) + '\n');
emit('product-lockup.svg', logo.productLockupSvg() + '\n');
emit('product-lockup-plate.svg', logo.productLockupSvg({ plate: true }) + '\n');
emit('product-lockup-stacked.svg', logo.productLockupStackedSvg() + '\n');

const shadowDefs =
  '<defs><filter id="s" x="-20%" y="-20%" width="140%" height="150%">' +
  '<feDropShadow dx="0" dy="4" stdDeviation="4" flood-color="#000" flood-opacity="0.35"/></filter></defs>';

for (const name of ICON_NAMES) {
  emit(`svg/icons/${name}.svg`, iconSvg(name, { color: colors.white, accent: colors.green }) + '\n');
  for (const state of ['default', 'hover', 'active'] as const) {
    const fill = state === 'active' ? colors.greenStrong : colors.navy;
    const bar = state === 'active' ? colors.navy : state === 'hover' ? colors.green : colors.greenStrong;
    const barW = state === 'hover' ? 49.6 : 20.8;
    const accent = state === 'active' ? colors.white : colors.green;
    const outline =
      state === 'hover'
        ? `<rect x="1.6" y="1.6" width="76.8" height="76.8" rx="12.8" fill="none" stroke="${colors.green}" stroke-width="3.2"/>`
        : '';
    const icon = iconSvg(name, { color: colors.white, accent })
      .replace(/^<svg[^>]*>/, '')
      .replace(/<\/svg>$/, '');
    emit(
      `svg/buttons/${name}-${state}.svg`,
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-8 -6 96 100" width="96" height="100">${shadowDefs}` +
        `<g filter="url(#s)"><rect width="80" height="80" rx="14.4" fill="${fill}"/>${outline}</g>` +
        `<g transform="translate(18 15) scale(1.833)" fill="none" stroke="${colors.white}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${icon}</g>` +
        `<rect x="${40 - barW / 2}" y="67.2" width="${barW}" height="4" rx="2" fill="${bar}"/></svg>\n`,
    );
  }
}
emit('svg/markers/evac-route-default.svg', evacMarkerSvg('default') + '\n');
emit('svg/markers/evac-route-active.svg', evacMarkerSvg('active') + '\n');
emit('svg/markers/info-default.svg', infoMarkerSvg('default') + '\n');
emit('svg/markers/info-attention.svg', infoMarkerSvg('attention') + '\n');
for (const name of SIGN_NAMES)
  for (const style of ['A', 'B'] as const) emit(`svg/signs/${name}-${style}.svg`, signSvg(name, style) + '\n');

